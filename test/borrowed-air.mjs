import test from 'node:test';
import assert from 'node:assert/strict';
import {newLedger,extract} from '../dist/mining.mjs';
import {restoreAir,airEpisode,acceptAir,deliverAir} from '../dist/borrowed-air.mjs';
for(const ally of ['Lantern Guild','Wakekeepers'])for(const choice of ['clinic','condenser'])test(ally+' / '+choice,()=>{
 let s={...newLedger(),campaign:{stage:'signal'},air:restoreAir()};
 assert.equal(airEpisode(s),null);
 assert.equal(acceptAir(s),false);
 s.campaign={stage:'complete',ally};
 assert.equal(acceptAir(s),true);
 assert.equal(acceptAir(s),false);
 assert.match(deliverAir(s,2,choice),/required/);
 extract(s,2,'relay');
 assert.match(deliverAir(s,1,choice),/Veyra/);
 assert.match(deliverAir(s,2,'invalid'),/valid/);
 assert.equal(s.ore[2],4);
 s=JSON.parse(JSON.stringify(s));s.air=restoreAir(s.air);
 assert.match(deliverAir(s,2,choice),/delivered/);
 assert.equal(s.ore[2],0);
 assert.equal(s.credits,choice==='clinic'?80:100);
 s=JSON.parse(JSON.stringify(s));s.air=restoreAir(s.air);
 assert.equal(s.air.choice,choice);
 assert.equal(s.campaign.ally,ally);
 assert.match(deliverAir(s,2,choice),/No active/);
 assert.equal(s.credits,choice==='clinic'?80:100);
});
test('invalid completed choice is not restored',()=>assert.deepEqual(restoreAir({stage:'complete',choice:'bad'}),{stage:'available',choice:null}));
